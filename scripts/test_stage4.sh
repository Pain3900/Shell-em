#!/bin/sh
# Этап 4: команды ls, cd, head, clear на VFS с вложенными каталогами.
# 1) Стартовый скрипт показывает все режимы команд.
# 2) Ошибки подаются на обычный ввод: стартовый скрипт остановился бы
#    на первой ошибке, а в интерактивном режиме эмулятор продолжает
#    работу и показывает каждую.
cd "$(dirname "$0")/.." || exit 1
echo "=== Все режимы команд (стартовый скрипт) ==="
sh run.sh --vfs vfs/deep.json --script scripts/start_stage4.txt < /dev/null
echo
echo "=== Ошибки команд (ввод из файла) ==="
sh run.sh --vfs vfs/deep.json < scripts/stage4_errors.txt 2>&1
